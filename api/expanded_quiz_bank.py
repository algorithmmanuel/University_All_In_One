def expand(items):
    assert len(items) == 50
    result = []
    for i, (prompt, correct, wrong_a, wrong_b) in enumerate(items):
        options = [correct, wrong_a, wrong_b]
        shift = i % 3
        options = options[shift:] + options[:shift]
        result.append((prompt, options, options.index(correct),
                       f"The correct answer is: {correct}."))
    return result

